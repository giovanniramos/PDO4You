<?php

declare(strict_types=1);

require __DIR__ . '/../vendor/autoload.php';

/**
 * Demonstrating connection via DSN strings with automatic platform resolution.
 *
 * @title SQLite Driver
 * @order 13
 */

use PDO4You\PDO4You;

// Database connection parameters
$dbhost = __DIR__ . "/../data/pdo4you.db";

try {
    // 1. Setup & Connection: Initialize connection via DSN
    echo "<p class='step'>1. Setup: Connecting via DSN</p>";
    $dsn = "sqlite:" . $dbhost;
    $db = PDO4You::connect($dsn);

    $version = $db->getPdo()->query('SELECT sqlite_version()')->fetchColumn();
    echo "<p class='success'>✓ Connected successfully - SQLite Version: {$version}</p>";

    // Create the users table if it does not already exist
    $db->exec("
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name VARCHAR(100) NOT NULL,
            surname VARCHAR(100) NOT NULL
        )
    ");
    echo "<p class='success'>✓ Table 'users' created.</p>";

    // Clear existing records for demonstration purposes
    $db->exec("DELETE FROM users");

    // 2. Insert: Add a new user and retrieve the ID generated by SQLite
    echo "<p class='step'>2. Operations: Inserting user</p>";
    $db->exec(
        "INSERT INTO users (name, surname) VALUES (?, ?)",
        ['Bob', 'Jones']
    );

    $lastId = $db->lastId();
    echo "<p>Last inserted ID: <strong>{$lastId}</strong></p>";

    // 3. Verification: Display the resulting records
    echo "<p class='step'>3. Verification: Querying users</p>";
    $users = $db->select("SELECT * FROM users");

    echo "<p>Resulting records:</p>";
    echo "<pre>" . htmlspecialchars(print_r($users, true)) . "</pre>";

} catch (\Throwable $e) {
    echo "<div class='error'>";
    echo "<h3>An error occurred:</h3>";
    echo "<pre>" . htmlspecialchars($e->getMessage()) . "</pre>";
    echo "</div>";
}

<?php

declare(strict_types=1);

require_once __DIR__ . '/../autoload.php';

/**
 * Demonstrating connection via DSN strings with automatic platform resolution.
 *
 * @title SQLite Driver
 * @order 13
 */

use PDO4You\PDO4You;

// Database file path configuration
$dataDir = __DIR__ . '/../data';
$dbFile = $dataDir . '/pdo4you.db';

try {
    // Ensure the data directory exists before initializing SQLite file database
    if (!is_dir($dataDir) && !mkdir($dataDir, 0775, true) && !is_dir($dataDir)) {
        throw new \RuntimeException("Unable to create data directory: {$dataDir}");
    }

    // 1. Setup & Connection: Initialize connection via DSN
    echo "<p class='step'>1. Setup: Connecting via DSN</p>";
    $dsn = 'sqlite:' . $dbFile;
    $db = PDO4You::connect($dsn);

    $version = (string) ($db->selectVal('SELECT sqlite_version()') ?: 'Unknown');
    echo "<p class='success'>✓ Connected successfully - SQLite Version: " . htmlspecialchars($version) . "</p>";

    // Create the users table if it does not already exist
    $db->exec("
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name VARCHAR(100) NOT NULL,
            surname VARCHAR(100) NOT NULL
        )
    ");
    echo "<p class='success'>✓ Table 'users' created.</p>";

    // Clear existing records for demonstration purposes
    $db->exec("DELETE FROM users");

    // 2. Insert: Add a new user and retrieve the ID generated by SQLite
    echo "<p class='step'>2. Operations: Inserting user</p>";
    $db->insert('users', [
        'name'    => 'Bob',
        'surname' => 'Jones',
    ]);

    $lastId = $db->lastId();
    echo "<p>Last inserted ID: <strong>" . htmlspecialchars($lastId) . "</strong></p>";

    // 3. Verification: Display the resulting records
    echo "<p class='step'>3. Verification: Querying users</p>";
    $users = $db->select("SELECT id, name, surname FROM users");

    echo "<p>Resulting records:</p>";
    echo "<pre>" . htmlspecialchars(print_r($users, true)) . "</pre>";

} catch (\Throwable $e) {
    echo "<div class='error'>";
    echo "<h3>An error occurred:</h3>";
    echo "<pre>" . htmlspecialchars($e->getMessage()) . "</pre>";
    echo "</div>";
}

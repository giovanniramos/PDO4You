<?php

declare(strict_types=1);

require_once __DIR__ . '/../vendor/autoload.php';

/**
 * Demonstrating connection via DSN strings with automatic platform resolution.
 *
 * @title SQL Server Driver
 * @order 14
 */

use PDO4You\PDO4You;

// Database connection parameters
$dbhost = getenv('DB_SQLSRV_HOST') ?: '.\SQLEXPRESS';
$dbuser = getenv('DB_SQLSRV_USER') ?: null;
$dbpass = getenv('DB_SQLSRV_PASS') ?: null;
$dbname = getenv('DB_SQLSRV_NAME') ?: 'pdo4you';

try {
    // 1. Setup & Connection: Initialize connection via DSN
    echo "<p class='step'>1. Setup: Connecting via DSN</p>";
    $dsn = "sqlsrv:Server={$dbhost};Database={$dbname};TrustServerCertificate=true";
    $db = PDO4You::connect($dsn, $dbuser, $dbpass);

    $version = $db->selectVal("
        SELECT CONCAT('Microsoft SQL Server ', CAST(SERVERPROPERTY('ProductVersion') AS NVARCHAR(128)))
    ") ?: 'Unknown';

    echo "<p class='success'>✓ Connected successfully - Server Version: "
        . htmlspecialchars((string) $version, ENT_QUOTES, 'UTF-8')
        . "</p>";

    // Create the users table if it does not already exist
    $db->exec("
        IF NOT EXISTS (
            SELECT 1
            FROM sys.tables t
            JOIN sys.schemas s ON t.schema_id = s.schema_id
            WHERE t.name = 'users' AND s.name = 'dbo'
        )
        BEGIN
            CREATE TABLE dbo.users (
                id INT IDENTITY(1,1) PRIMARY KEY,
                name VARCHAR(100) NOT NULL,
                surname VARCHAR(100) NOT NULL
            );
        END
    ");
    echo "<p class='success'>✓ Table 'users' created.</p>";

    // Clear existing records for demonstration purposes
    $db->exec("DELETE FROM dbo.users");

    // 2. Insert: Add a new user and retrieve the ID generated by SQL Server
    echo "<p class='step'>2. Operations: Inserting user</p>";
    $db->insert('dbo.users', [
        'name'    => 'Bob',
        'surname' => 'Jones',
    ]);

    $lastId = $db->lastId();
    echo "<p>Last inserted ID: <strong>" . htmlspecialchars($lastId) . "</strong></p>";

    // 3. Verification: Display the resulting records
    echo "<p class='step'>3. Verification: Querying users</p>";
    $users = $db->select("SELECT id, name, surname FROM dbo.users");

    echo "<p>Resulting records:</p>";
    echo "<pre>" . htmlspecialchars(print_r($users, true)) . "</pre>";

} catch (\Throwable $e) {
    echo "<div class='error'>";
    echo "<h3>An error occurred:</h3>";
    echo "<pre>" . htmlspecialchars($e->getMessage()) . "</pre>";
    echo "</div>";
}
